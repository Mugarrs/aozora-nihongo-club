-- Pesan & kritik (papan publik)
create table if not exists feedback (
  id         bigint generated by default as identity primary key,
  name       text not null,
  msg        text not null,
  type       text not null default 'Saran',
  rating     int  not null default 0,
  likes      int  not null default 0,
  created_at timestamptz not null default now()
);

-- Pesan pribadi ke pengurus
create table if not exists private_messages (
  id         bigint generated by default as identity primary key,
  name       text not null,
  msg        text not null,
  created_at timestamptz not null default now()
);

-- Galeri dokumentasi
create table if not exists gallery (
  id         bigint generated by default as identity primary key,
  src        text not null,
  caption    text default '',
  created_at timestamptz not null default now()
);

-- Info pertemuan (1 baris saja, id = 1)
create table if not exists forum (
  id       int primary key default 1,
  hari     text default 'Kamis',
  tempat   text default 'C107',
  waktu    text default '15.30 – selesai',
  catatan  text default 'Bawa buku catatan & semangat.'
);
insert into forum (id) values (1) on conflict (id) do nothing;

-- =========================================================
-- IZIN AKSES (Row Level Security)
-- =========================================================
alter table feedback         enable row level security;
alter table private_messages enable row level security;
alter table gallery          enable row level security;
alter table forum            enable row level security;

-- feedback: semua orang boleh baca & tulis, boleh update likes, boleh hapus (admin sisi klien)
drop policy if exists fb_read   on feedback;
drop policy if exists fb_insert on feedback;
drop policy if exists fb_update on feedback;
drop policy if exists fb_delete on feedback;
create policy fb_read   on feedback for select using (true);
create policy fb_insert on feedback for insert with check (true);
create policy fb_update on feedback for update using (true);
create policy fb_delete on feedback for delete using (true);

-- private_messages
drop policy if exists pv_read   on private_messages;
drop policy if exists pv_insert on private_messages;
drop policy if exists pv_delete on private_messages;
create policy pv_read   on private_messages for select using (true);
create policy pv_insert on private_messages for insert with check (true);
create policy pv_delete on private_messages for delete using (true);

-- gallery
drop policy if exists g_read   on gallery;
drop policy if exists g_insert on gallery;
drop policy if exists g_delete on gallery;
create policy g_read   on gallery for select using (true);
create policy g_insert on gallery for insert with check (true);
create policy g_delete on gallery for delete using (true);

-- forum
drop policy if exists f_read   on forum;
drop policy if exists f_write  on forum;
create policy f_read  on forum for select using (true);
create policy f_write on forum for all using (true) with check (true);
